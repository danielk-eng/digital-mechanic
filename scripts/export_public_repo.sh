#!/usr/bin/env bash
# Build a clean copy of the git history for the PUBLIC GitHub repo (organisers' form 27.11: public, with history,
# open until the results; docs/REPO_ACCESS.md). Does not push.
# Every commit is kept one-to-one (no squash, empty-after-filter commits stay: --prune-empty never), dates and authors as
# they were; the export is deterministic, so re-running it after new commits only appends (fast-forward push).
# The commit history is kept; only paths that must never leave the stand are cut out of every commit:
# OEM manual text indexes (they were in git 26.11 between 4237dcc and 7f76f09; f29c03d carried the KAMAZ manual text inside
# data/index/extra_pages.jsonl.gz -- cut by the data/index/*.jsonl.gz glob), translated pages, PDFs, the KAMAZ mirror.
# Needs: git-filter-repo (pip install git-filter-repo), gitleaks (optional, for the final scan).
set -euo pipefail
SRC=${1:-$(git rev-parse --show-toplevel)}
OUT=$(realpath -m "${2:-$SRC/../_work/public-export}")
BRANCH=${BRANCH:-main}
rm -rf "$OUT"
git clone --quiet --no-local --single-branch --branch "$BRANCH" "$SRC" "$OUT"
cd "$OUT"
git filter-repo --force --quiet --prune-empty never --prune-degenerate never --invert-paths \
  --path-glob 'data/index/*.jsonl.gz' --path-glob 'data/i18n/pages_*.jsonl.gz' --path data/extra/pdf \
  --path-glob '*.pdf' --path-glob '*kamaz*' --path-glob '*KAMAZ*' --path-glob '*.m4a' --path-glob '*.wav' --path-glob '*.mp4' \
  --path-glob '.env' --path-glob '*.key' --path materials --path briefing --path STATUS.md --path PLAN.md \
  --path-glob '*.docx' --path-glob '*.zip' \
  --path data/official --path vendor/neurodvs_mock/data --path vendor/neurodvs_mock/mock_ml --path vendor/neurodvs_mock/mock_toir \
  --path vendor/neurodvs_mock/tests --path vendor/neurodvs_mock/tools --path vendor/neurodvs_mock/README.md \
  --path vendor/neurodvs_mock/openapi_ml.json --path vendor/neurodvs_mock/openapi_toir.json \
  --path vendor/neurodvs_mock/requirements.txt --path vendor/neurodvs_mock/.env.example
# task materials (organizers 27.11): the stub archive and the vehicle cards never appear in the public history either
# (only our vendor/neurodvs_mock/Dockerfile stays); the materials folder link is env-only (TASK_MATERIALS_URL) -> redacted
printf '%s\n' 'regex:https://disk\.yandex\.ru/d/[A-Za-z0-9_-]+==>${TASK_MATERIALS_URL}' > "$OUT/../replace.txt"
git filter-repo --force --quiet --prune-empty never --prune-degenerate never --replace-text "$OUT/../replace.txt"
# the six synthetic mock PDFs (data/mock/manuals, generated by us) go too: *.pdf is cut wholesale to be safe
git reflog expire --expire=now --all && git gc --quiet --prune=now --aggressive
left=$(git log --all --name-only --format= | sort -u | grep -iE 'jsonl\.gz$|\.pdf$|\.docx$|\.zip$|kamaz|\.m4a$|^materials/|^briefing/|^STATUS\.md$|^\.env$|^data/official/|^vendor/neurodvs_mock/(data|mock_|tests|tools|openapi|README|requirements|\.env)' || true)
if [ -n "$left" ]; then echo "FORBIDDEN PATHS LEFT:"; echo "$left"; exit 1; fi
if git log --all -p | grep -qi 'камаз-\?[0-9]\{4\}\|kamaz-[0-9]\{4\}'; then echo "warning: KAMAZ model names in diffs (text mentions only?)"; fi
if git log --all -p | grep -q "disk\.yandex\.ru/d/[A-Za-z0-9_-]\{6,\}"; then echo "materials link left in history"; exit 1; fi
echo "commits: $(git rev-list --count HEAD)  size: $(du -sh .git | cut -f1)"
if command -v gitleaks >/dev/null; then gitleaks git --redact --no-banner . ; else echo "gitleaks not installed: run it before the push"; fi
echo "clean copy: $OUT  (push: git remote add origin git@github.com:<owner>/<repo>.git && git push -u origin $BRANCH)"
