"""Tool signatures the sprint agent should expose. Bodies wait for official data."""

from __future__ import annotations

from typing import Protocol

from digital_mechanic.schemas import CheckResult, TicketAck, TicketDraft, Vehicle


class MechanicTools(Protocol):
    def get_vehicle(self, vehicle_id: str) -> Vehicle: ...
    def list_checks(self, vehicle_id: str) -> list[str]: ...
    def get_check(self, vehicle_id: str, session_id: str) -> CheckResult: ...
    def search_manual(self, engine_type: str, query: str) -> list[dict]: ...
    def create_toir_ticket(self, draft: TicketDraft) -> TicketAck: ...
